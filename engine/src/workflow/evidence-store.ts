const POLICY = ROOT_POLICY.workflow.evidenceStore;

/** The schema a manifest declares. */
export const EVIDENCE_MANIFEST_SCHEMA = schemaId("evidence-manifest", 1);

/** Why `path` cannot be a recorded path, or `undefined`: never absolute, escaping or empty (the one relative-path owner), never inside git's own folders. */
function recordedPathViolation(path: string): string | undefined {
  const kinds = relativePathViolationKinds(path);
  if (kinds.length > 0) return kinds.join(", ");
  const forbidden = path.split("/").find((segment) => (POLICY.forbiddenSegments as readonly string[]).includes(segment.toLowerCase()));
  if (forbidden !== undefined) return `a ${forbidden} segment (git's own files are never evidence)`;
  // A path git would read as pathspec MAGIC (`:!x`, `:/`, `:(glob)…`) names more than one file to every git verb it
  // reaches (security H-2: the ingest's `git add` staged the whole tree); git is also told to read every path literally.
  return path.startsWith(":") ? "a leading ':' (git pathspec magic)" : undefined;
}

/** A recorded path: repository-relative, `/`-separated, normalized, never absolute, escaping or inside git's folders. */
const RECORDED_PATH = z.string().superRefine((path, context) => {
  const violation = recordedPathViolation(path);
  if (violation !== undefined) context.addIssue({ code: "custom", message: `not a recorded path: ${violation}` });
});

const ENTRY_SCHEMA = z.strictObject({
  path: RECORDED_PATH,
  sha256: z.string().regex(SHA256_HEX_REGEX),
  size: z.number().int().nonnegative(),
  /** The file's mode as git models it: `0755` when it was executable when stored, else `0644` (the same manifest whatever the umask). */
  mode: z.enum(["0644", "0755"]),
});

const MANIFEST_SCHEMA = z.strictObject({
  schema: z.literal(EVIDENCE_MANIFEST_SCHEMA),
  entries: z.array(ENTRY_SCHEMA),
});

/** One stored file, as its manifest records it. */
export type EvidenceEntry = z.infer<typeof ENTRY_SCHEMA>;
/** A manifest document. */
export type EvidenceManifest = Readonly<{ schema: typeof EVIDENCE_MANIFEST_SCHEMA; entries: readonly EvidenceEntry[] }>;
/** A recorded entry with the manifest (repository-relative) that records it. */
export type RecordedEvidence = EvidenceEntry & Readonly<{ manifest: string }>;

/** The engine CLI verbs, as data (refusals and docs print them). */
export const EVIDENCE_VERBS = deepFreeze(["ingest", "verify", "materialize"] as const);

/** `path` as a recorded path, or a typed refusal (`evidence_path_invalid`). */
function recordedPath(path: string): string {
  const violation = recordedPathViolation(path);
  if (violation !== undefined) throw new InputError(`${JSON.stringify(path)} is not a repository-relative evidence path: ${violation}`, "evidence_path_invalid");
  return path;
}

/** The evidence folder a manifest governs: `<the manifest's folder>/<folderName>` (every path it records lies under it). */
function evidenceFolderOf(manifest: string): string {
  const folder = posix.dirname(manifest);
  return folder === "." ? POLICY.folderName : `${folder}/${POLICY.folderName}`;
}

/**
 * Whether recorded key `key` names a file under recorded folder `folder`: a
 * question about the manifest's own keys (each a validated, normalized
 * repository-relative shape), never about where a place on the disk lies —
 * every read and write of the disk is contained by descriptor and identity.
 */
function keyUnder(key: string, folder: string): boolean {
  return key.startsWith(`${folder}/`);
}

/** Whether `path` lies in `manifest`'s evidence folder. */
function inEvidenceFolder(manifest: string, path: string): boolean {
  return keyUnder(path, evidenceFolderOf(manifest));
}

// ── The store ────────────────────────────────────────────────────────────

/** Where the store is now and what named it (the boot read; the read-only setting signal shows it). */
export function evidenceStoreSetting(): PrivateHomeSetting {
  return privateHomeSetting(EVIDENCE_HOME);
}

/** Where the store is for a process about to use it (a process under test without `HARNESS_EVIDENCE_HOME` is refused: `evidence_store_unset_under_test`). */
export function evidenceStoreLocation(): string {
  return privateHomeLocation(EVIDENCE_HOME);
}

/** An admitted store: its folder, and the immutable owner's authority over its objects. */
export type EvidenceStore = Readonly<{ location: ResolvedAbsolutePath; authority: ReceiptAuthority }>;

/**
 * ADMIT the store at `location` for the repository at `top`: the one
 * private-home admission (a real private folder of this user, disjoint by
 * identity from the repository and the system temp folder), then the
 * immutable owner's authority over its objects folder.
 */
export function admitEvidenceStore(location: string, top: string): EvidenceStore {
  const store = admitPrivateHome(EVIDENCE_HOME, location, [
    { path: top, what: "the repository" },
    { path: tmpdir(), what: "the system temp folder" },
  ]);
  // The objects' private folder chain is made HERE, once, by the immutable
  // owner (its private-folder creator runs only under an admitted runtime:
  // the one this process holds, or one admitted for this step); a later write
  // only opens it.
  const objects = `${POLICY.objects.root}/${POLICY.objects.namespace}/sha256`;
  const admitted = (): ReceiptAuthority => {
    ensureReceiptAuthority(store, objects);
    return ensureReceiptAuthority(store, POLICY.objects.root);
  };
  return deepFreeze({ location: store, authority: hasAdmittedNodeRuntime() ? admitted() : withAdmittedNodeRuntime(configuredRuntimeAdmission(), admitted) });
}

/** The verified bytes of `digest`, or `undefined` when the store holds no object for it. */
function readObject(store: EvidenceStore, digest: string): Buffer | undefined {
  return readContentAddressed(store.authority, { namespace: POLICY.objects.namespace, extension: POLICY.objects.extension, sha256: digest });
}

/**
 * KEEP `bytes` AS EVIDENCE and answer their sha256 — the store's one door for
 * evidence no tracked file holds (a reproduction run's output: the attempt log
 * names it by this digest, src/workflow/flake-cli.ts).
 */
export function keepEvidenceBytes(store: EvidenceStore, bytes: Uint8Array): string {
  putObject(store, bytes);
  return sha256(bytes);
}

/** Store `bytes`: created, or already present with exactly these bytes (the immutable owner refuses anything else). */
function putObject(store: EvidenceStore, bytes: Uint8Array): "written" | "present" {
  const written = writeImmutableEvidence(store.authority, { mode: "content-addressed", namespace: POLICY.objects.namespace, extension: POLICY.objects.extension, bytes, contentKind: "blob" });
  return written.disposition === "created" ? "written" : "present";
}

// ── Manifests ────────────────────────────────────────────────────────────

/** A file's mode as git models it (and the manifest records it): executable or not, never the umask's bits. */
function gitFileMode(mode: number): EvidenceEntry["mode"] {
  return (mode & 0o111) === 0 ? "0644" : "0755";
}

/**
 * Parse and validate the manifest at repository path `manifest`. Entries
 * must be sorted by path, each path once, and every one inside the
 * manifest's evidence folder (`evidence_entry_outside_manifest`).
 */
export function parseEvidenceManifest(text: string, manifest: string): EvidenceManifest {
  let value: unknown;
  try {
    value = JSON.parse(text);
  } catch (error) {
    throw new InputError(`${manifest} is not JSON: ${error instanceof Error ? error.message : String(error)}`, "evidence_manifest_invalid");
  }
  const parsed = MANIFEST_SCHEMA.safeParse(value);
  if (!parsed.success) throw new InputError(`${manifest} is not a ${EVIDENCE_MANIFEST_SCHEMA} document: ${parsed.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`).join("; ")}`, "evidence_manifest_invalid");
  const entries = parsed.data.entries;
  for (let index = 0; index < entries.length; index += 1) {
    const entry = entries[index]!;
    if (!inEvidenceFolder(manifest, entry.path)) {
      throw new SecurityError(`${manifest} records ${entry.path}, outside its evidence folder ${evidenceFolderOf(manifest)}/: a manifest only ever names files of its own folder`, "evidence_entry_outside_manifest");
    }
    if (index > 0 && entries[index - 1]!.path >= entry.path) throw new InputError(`${manifest}: entries are not sorted by path, each path once (${entries[index - 1]!.path} before ${entry.path})`, "evidence_manifest_invalid");
  }
  return deepFreeze({ schema: EVIDENCE_MANIFEST_SCHEMA, entries });
}

/** A manifest document's text, in the one layout: sorted, one entry per line, final newline. */
export function evidenceManifestText(entries: readonly EvidenceEntry[]): string {
  const sorted = [...entries].sort((left, right) => (left.path < right.path ? -1 : left.path > right.path ? 1 : 0));
  const lines = sorted.map(({ path, sha256: digest, size, mode }) => `    ${JSON.stringify({ path, sha256: digest, size, mode })}`);
  return `{\n  "schema": ${JSON.stringify(EVIDENCE_MANIFEST_SCHEMA)},\n  "entries": [${lines.length === 0 ? "" : `\n${lines.join(",\n")}\n  `}]\n}\n`;
}

/**
 * Every manifest the repository at `top` TRACKS that is on the disk
 * (repository-relative, sorted): only a tracked manifest steers the generated
 * ignore rule, verify and materialize — an untracked file named like one
 * could otherwise hide its folder from `git status` and every staged-tree
 * guard (security re-verification, LOW). An ingest stages the manifest it
 * writes, so its folder's ignore rule never drops in between (correctness
 * E1). An UNTRACKED manifest is refused by name (`evidence_manifest_untracked`):
 * stage it, or remove it. An unstaged deletion holds no manifest to read.
 */
export function evidenceManifests(top: string): readonly string[] {
  const tracked = presentTrackedFiles(top);
  const owned = ownedFiles(top);
  if (tracked === undefined || owned === undefined) throw new InputError(`not inside a git working tree: ${top}`, "evidence_repository_missing");
  const isManifest = (path: string): boolean => posix.basename(path) === POLICY.manifestName;
  const trackedSet = new Set(tracked);
  const untracked = owned.filter((path) => isManifest(path) && !trackedSet.has(path));
  if (untracked.length > 0) {
    throw new InputError(`untracked evidence manifest(s) ${untracked.join(", ")}: only a tracked manifest steers the ignore rule, verify and materialize — stage it (an ingest stages its own) or remove it`, "evidence_manifest_untracked");
  }
  return deepFreeze(tracked.filter((path) => isManifest(path) && readContained(top, path) !== undefined).sort());
}

function readManifest(top: string, manifest: string): EvidenceManifest {
  const read = readContained(top, recordedPath(manifest));
  if (read === undefined) throw new InputError(`${manifest} does not exist`, "evidence_manifest_missing");
  return parseEvidenceManifest(read.bytes.toString("utf8"), manifest);
}

/**
 * Every recorded path of the given manifests (default: every tracked one),
 * with its entry. A path two manifests record is refused
 * (`evidence_manifest_conflict`): a citation must name one set of bytes.
 */
export function recordedEvidence(top: string, manifests: readonly string[] = evidenceManifests(top)): ReadonlyMap<string, RecordedEvidence> {
  const recorded = new Map<string, RecordedEvidence>();
  for (const manifest of manifests) {
    for (const entry of readManifest(top, manifest).entries) {
      const other = recorded.get(entry.path);
      if (other !== undefined) throw new InputError(`${entry.path} is recorded by both ${other.manifest} and ${manifest}`, "evidence_manifest_conflict");
      recorded.set(entry.path, deepFreeze({ ...entry, manifest }));
    }
  }
  return recorded;
}

/** The recorded entries `path` names: the entry itself, or every entry under it when it is a folder of recorded paths. */
export function recordedUnder(recorded: ReadonlyMap<string, RecordedEvidence>, path: string): readonly RecordedEvidence[] {
  const exact = recorded.get(path);
  if (exact !== undefined) return [exact];
  return [...recorded.values()].filter((entry) => keyUnder(entry.path, path));
}

// ── Contained reads and writes inside the checkout ──────────────────────

/** The checkout's top, resolved (every contained walk starts at it). */
function resolvedTop(top: string): ResolvedAbsolutePath {
  return resolveLocation(realpathSync(top), "the repository");
}

/** Run `use` with the folder holding repository path `path`, reached from `top` without following a link (`undefined` when a folder on the way is missing and `create` is false). */
function withParentOf<T>(top: string, path: string, create: boolean, use: (folder: ContainedFolder, name: string) => T): T | undefined {
  const segments = path.split("/");
  const name = segments.pop()!;
  let folder: ContainedFolder | undefined;
  try {
    folder = openContainedFolder(resolvedTop(top), segments, create);
  } catch (error) {
    throw asEvidenceRefusal(error, path);
  }
  if (folder === undefined) return undefined;
  try {
    return use(folder, name);
  } finally {
    folder.close();
  }
}

/** A path-identity refusal, named for the evidence path it stopped. */
function asEvidenceRefusal(error: unknown, path: string): unknown {
  if (error instanceof HarnessError && (error.code === "path_through_link" || error.code === "path_not_a_folder" || error.code === "path_outside_root")) {
    return new SecurityError(`${path}: ${error.message}`, "evidence_path_through_link");
  }
  return error;
}

/**
 * The bytes and mode of the regular file at repository path `path`, read
 * through a descriptor opened without following a link, in a folder reached
 * the same way — what is checked is what is read (no check-then-read race).
 * `undefined` when it does not exist; a link or a special file is refused.
 */
function readContained(top: string, path: string): Readonly<{ bytes: Buffer; mode: number }> | undefined {
  return withParentOf(top, path, false, (folder, name) => {
    let descriptor: number;
    try {
      descriptor = openSync(join(folder.path, name), constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (code === "ENOENT") return undefined;
      if (code === "ELOOP") throw new SecurityError(`${path} is a link; a link is never stored or read as evidence`, "evidence_not_regular_file");
      throw error;
    }
    try {
      const stat = fstatSync(descriptor);
      if (!stat.isFile()) throw new InputError(`${path} is not a regular file (a folder, a link or a special file is never read as one)`, "evidence_not_regular_file");
      return { bytes: readFileSync(descriptor), mode: stat.mode };
    } finally {
      closeSync(descriptor);
    }
  });
}

/** Every regular file `path` (repository-relative) names under `top`: itself, or every regular file under a folder (sorted). A link anywhere is refused. */
function filesAt(top: string, path: string): readonly string[] {
  let folder: ContainedFolder | undefined;
  try {
    folder = openContainedFolder(resolvedTop(top), path.split("/"), false);
  } catch (error) {
    // The last name is not a folder: a regular file is itself (a special file is refused by the read).
    if (error instanceof HarnessError && error.code === "path_not_a_folder" && readContained(top, path) !== undefined) return [path];
    throw asEvidenceRefusal(error, path);
  }
  if (folder === undefined) throw new InputError(`${path} does not exist`, "evidence_path_missing");
  let entries;
  try {
    entries = readdirSync(folder.path, { withFileTypes: true });
  } finally {
    folder.close();
  }
  return entries.sort((left, right) => (left.name < right.name ? -1 : left.name > right.name ? 1 : 0)).flatMap((entry) => {
    if (entry.isDirectory()) return filesAt(top, `${path}/${entry.name}`);
    if (entry.isFile()) return [`${path}/${entry.name}`];
    throw new InputError(`${path}/${entry.name} is not a regular file or a folder (a link or a special file is never stored)`, "evidence_not_regular_file");
  });
}

// ── The ignore rule ──────────────────────────────────────────────────────

/** The generated block of the root ignore file: one rule per tracked manifest's evidence folder (sorted). */
function evidenceIgnoreBlock(manifests: readonly string[]): string {
  const rules = [...new Set(manifests.map((manifest) => `/${evidenceFolderOf(manifest)}/`))].sort();
  return [POLICY.ignoreBlock.begin, ...rules, POLICY.ignoreBlock.end].join("\n");
}

/**
 * The ignore file's text with its generated block made current: replaced in
 * place, appended when absent — and removed when no manifest is tracked (a
 * tree without evidence carries no block).
 */
function withEvidenceIgnoreBlock(text: string, block: string | undefined): string {
  const begin = text.indexOf(POLICY.ignoreBlock.begin);
  const end = text.indexOf(POLICY.ignoreBlock.end);
  const present = begin !== -1 && end !== -1 && end > begin;
  if (block === undefined) {
    if (!present) return text;
    const after = text.slice(end + POLICY.ignoreBlock.end.length);
    return `${text.slice(0, begin)}${after.startsWith("\n") ? after.slice(1) : after}`;
  }
  if (!present) return `${text}${text.length === 0 || text.endsWith("\n") ? "" : "\n"}${block}\n`;
  return `${text.slice(0, begin)}${block}${text.slice(end + POLICY.ignoreBlock.end.length)}`;
}

/** What the ignore arm did: `changed` names the ignore file when a write rewrote it or a check found it stale. */
export type EvidenceIgnoreReport = Readonly<{ status: "current" | "regenerated" | "stale" | "absent"; converged: boolean; changed: readonly string[]; rules: readonly string[] }>;

/**
 * THE GENERATED IGNORE RULE: the root ignore file's evidence block, derived
 * from the evidence manifests (tracked, on the disk). With `write`, a stale
 * block is rewritten (`harness sync`, and every ingest; the file is created
 * when evidence needs it); without it, the report says whether it is current
 * (`harness check`). A tree with neither manifests nor an ignore file has
 * nothing to keep current (`absent`).
 */
export function syncEvidenceIgnore(top: string, write: boolean, manifests: readonly string[] = evidenceManifests(top)): EvidenceIgnoreReport {
  const file = POLICY.ignoreBlock.file;
  const block = manifests.length === 0 ? undefined : evidenceIgnoreBlock(manifests);
  const rules = block === undefined ? [] : block.split("\n").slice(1, -1);
  const current = readContained(top, file)?.bytes.toString("utf8");
  if (current === undefined && block === undefined) return deepFreeze({ status: "absent", converged: true, changed: [], rules });
  const desired = withEvidenceIgnoreBlock(current ?? "", block);
  if (desired === current) return deepFreeze({ status: "current", converged: true, changed: [], rules });
  if (!write) return deepFreeze({ status: "stale", converged: false, changed: [file], rules });
  const written = withParentOf(top, file, false, (folder, name) => atomicWriteFile(join(folder.path, name), desired, { createMode: ROOT_POLICY.filesystem.rawFileModes.source, createParentDirectories: false }));
  if (written === undefined || !written.success) throw new HarnessError(`${file} could not be written: ${written?.reason ?? "missing"}`, "evidence_ignore_write_failed");
  return deepFreeze({ status: "regenerated", converged: true, changed: [file], rules });
}

// ── The verbs ────────────────────────────────────────────────────────────

export type EvidenceIngestReport = Readonly<{
  store: string;
  manifest: string;
  files: number;
  bytes: number;
  /** Objects this ingest stored. */
  written: number;
  /** Objects the store already held (the same bytes, whoever stored them). */
  present: number;
  /** Recorded paths this ingest added to the manifest (an already recorded path with the same bytes is not counted). */
  recorded: number;
}>;

/**
 * INGEST: store every regular file `paths` name (repository-relative, inside
 * `manifest`'s evidence folder; a folder: every regular file under it) and
 * record each in `manifest` (created when absent). IDEMPOTENT: a path already
 * recorded with the same bytes changes nothing, and a recorded path is never
 * given OTHER bytes (`evidence_replace_refused`, naming both digests) — a
 * citation keeps naming what its author saw. The files stay where they are:
 * dropping them from the tree is the operator's next step; git already
 * ignores them (the generated rule is written here too).
 */
export function ingestEvidence(top: string, paths: readonly string[], manifest: string, store: EvidenceStore = admitEvidenceStore(evidenceStoreLocation(), top)): EvidenceIngestReport {
  if (paths.length === 0) throw new InputError("ingest needs at least one path to store", "evidence_usage");
  recordedPath(manifest);
  if (posix.basename(manifest) !== POLICY.manifestName) throw new InputError(`a manifest is named ${POLICY.manifestName} (found wherever git tracks one), not ${posix.basename(manifest)}`, "evidence_manifest_name");
  for (const path of paths.map(recordedPath)) {
    if (path !== evidenceFolderOf(manifest) && !inEvidenceFolder(manifest, path)) {
      throw new InputError(`${path} is outside ${manifest}'s evidence folder ${evidenceFolderOf(manifest)}/; a manifest records only files of its own folder`, "evidence_entry_outside_manifest");
    }
  }
  const files = [...new Set(paths.flatMap((path) => filesAt(top, path)))].sort();
  // ONE INGEST AT A TIME per checkout: the manifest is read, extended and
  // written back, and two ingests interleaving that would lose entries (correctness E3).
  return withFileLock(join(top, statePath(INGEST_LOCK_NAME)), (message, details) => new HarnessError(`another ingest is writing this checkout's evidence manifests (${message})`, "evidence_ingest_busy", true, details),
    () => ingestUnderLock(top, files, manifest, store), { holder: `evidence ingest (${manifest})` });
}

/** The lock every ingest of a checkout holds (under its state folder, never tracked). */
const INGEST_LOCK_NAME = "evidence-ingest.lock";

function ingestUnderLock(top: string, files: readonly string[], manifest: string, store: EvidenceStore): EvidenceIngestReport {
  const existing = readContained(top, manifest) === undefined ? [] : readManifest(top, manifest).entries;
  const entries = new Map(existing.map((entry) => [entry.path, entry]));
  // Refuse a replacement before anything is stored: the whole ingest is one decision.
  const reads = files.map((file) => {
    const read = readContained(top, file);
    if (read === undefined) throw new InputError(`${file} does not exist`, "evidence_path_missing");
    const digest = sha256(read.bytes);
    const before = entries.get(file);
    if (before !== undefined && before.sha256 !== digest) {
      throw new InputError(`${file} is recorded with sha256 ${before.sha256}; its bytes now hash to ${digest}. A recorded path never names other bytes: record the new file under a new path`, "evidence_replace_refused");
    }
    return { file, read, digest, before };
  });
  const tally = { written: 0, present: 0, bytes: 0, recorded: 0 };
  for (const { file, read, digest, before } of reads) {
    tally[putObject(store, read.bytes)] += 1;
    tally.bytes += read.bytes.length;
    if (before === undefined) {
      entries.set(file, { path: file, sha256: digest, size: read.bytes.length, mode: gitFileMode(read.mode) });
      tally.recorded += 1;
    }
  }
  if (tally.recorded > 0 || existing.length === 0) {
    const written = withParentOf(top, manifest, true, (folder, name) => atomicWriteFile(join(folder.path, name), evidenceManifestText([...entries.values()]), { createMode: ROOT_POLICY.filesystem.rawFileModes.evidence, createParentDirectories: false }));
    if (written === undefined || !written.success) throw new HarnessError(`the manifest ${manifest} could not be written: ${written?.reason ?? "missing"}`, "evidence_manifest_write_failed");
  }
  // The manifest this ingest owns is STAGED (that one path, nothing else): only a tracked manifest steers the ignore rule.
  gitOutput(configuredGitRepository({}, top), ["--literal-pathspecs", "add", "--", manifest]);
  syncEvidenceIgnore(top, true);
  const report = deepFreeze({ store: store.location, manifest, files: files.length, bytes: tally.bytes, written: tally.written, present: tally.present, recorded: tally.recorded });
  auditEvent("evidence-ingested", report);
  return report;
}

export type EvidenceVerifyReport = Readonly<{
  store: string;
  manifests: readonly string[];
  entries: number;
  bytes: number;
  /** Recorded paths whose object is absent from the store. */
  missing: readonly string[];
  /** Recorded paths whose object does not hold the recorded bytes or size. */
  corrupt: readonly string[];
  /** Recorded paths whose object the immutable owner refuses to read: a link, a widened mode, a second name, another owner. */
  unsafe: readonly string[];
  allPresent: boolean;
}>;

/** VERIFY: every entry of `manifests` (default: every tracked one) has its object in `store`, private, of the recorded size and digest. */
export function verifyEvidence(top: string, manifests: readonly string[] = evidenceManifests(top), store: EvidenceStore = admitEvidenceStore(evidenceStoreLocation(), top)): EvidenceVerifyReport {
  const recorded = recordedEvidence(top, manifests.map(recordedPath));
  const missing: string[] = [];
  const corrupt: string[] = [];
  const unsafe: string[] = [];
  let bytes = 0;
  for (const entry of recorded.values()) {
    let object: Buffer | undefined;
    try {
      object = readObject(store, entry.sha256);
    } catch (error) {
      if (!(error instanceof HarnessError)) throw error;
      (error.code === "receipt_content_address_mismatch" ? corrupt : unsafe).push(entry.path);
      continue;
    }
    if (object === undefined) missing.push(entry.path);
    else if (object.length !== entry.size) corrupt.push(entry.path);
    else bytes += object.length;
  }
  const report = deepFreeze({ store: store.location, manifests: [...manifests], entries: recorded.size, bytes, missing, corrupt, unsafe, allPresent: missing.length === 0 && corrupt.length === 0 && unsafe.length === 0 });
  auditEvent("evidence-verified", { store: store.location, manifests: manifests.length, entries: recorded.size, bytes, missing: missing.length, corrupt: corrupt.length, unsafe: unsafe.length });
  return report;
}

export type EvidenceMaterializeReport = Readonly<{
  store: string;
  /** Recorded paths written at their path. */
  written: readonly string[];
  /** Recorded paths whose file was already there with the recorded bytes. */
  unchanged: readonly string[];
}>;

/**
 * MATERIALIZE: write each recorded file `paths` name (a recorded path, or a
 * folder of recorded paths) back at its recorded path under `top`, with its
 * recorded mode, from verified bytes, into folders reached without following
 * a link (missing ones made one level at a time). A file already there with
 * other bytes is refused (`evidence_materialize_conflict`), never
 * overwritten; nothing is written when any named path is unrecorded, any
 * object is missing, or the generated ignore rule is stale
 * (`evidence_ignore_stale`: the copies would not be ignored).
 */
export function materializeEvidence(top: string, paths: readonly string[], store: EvidenceStore = admitEvidenceStore(evidenceStoreLocation(), top)): EvidenceMaterializeReport {
  if (paths.length === 0) throw new InputError("materialize needs at least one recorded path (or a folder of them)", "evidence_usage");
  const manifests = evidenceManifests(top);
  if (!syncEvidenceIgnore(top, false).converged) {
    throw new InputError(`${POLICY.ignoreBlock.file}'s generated evidence block is stale, so materialized copies would not be ignored; run harness sync first`, "evidence_ignore_stale");
  }
  const recorded = recordedEvidence(top, manifests);
  const entries = new Map<string, RecordedEvidence>();
  for (const path of paths.map(recordedPath)) {
    const named = recordedUnder(recorded, path);
    if (named.length === 0) throw new InputError(`${path} is not a recorded path (or a folder of recorded paths) of any manifest`, "evidence_not_recorded");
    for (const entry of named) entries.set(entry.path, entry);
  }
  const plan = [...entries.values()].sort((left, right) => (left.path < right.path ? -1 : 1)).map((entry) => {
    const bytes = readObject(store, entry.sha256);
    if (bytes === undefined) throw new HarnessError(`${entry.path}: its object ${entry.sha256} is not in the store ${store.location} (run harness evidence verify)`, "evidence_object_missing");
    const present = readContained(top, entry.path);
    if (present !== undefined && sha256(present.bytes) !== entry.sha256) {
      throw new InputError(`${entry.path} exists with other content; move it away first (materialize never overwrites a different file)`, "evidence_materialize_conflict");
    }
    return { entry, bytes, present: present !== undefined };
  });
  const written: string[] = [];
  const unchanged: string[] = [];
  for (const { entry, bytes, present } of plan) {
    if (present) {
      unchanged.push(entry.path);
      continue;
    }
    const result = withParentOf(top, entry.path, true, (folder, name) => atomicWriteFile(join(folder.path, name), bytes, { exactMode: Number.parseInt(entry.mode, 8), createParentDirectories: false }));
    if (result === undefined || !result.success) throw new HarnessError(`${entry.path} could not be written: ${result?.reason ?? "missing"}`, "evidence_materialize_failed");
    written.push(entry.path);
  }
  const report = deepFreeze({ store: store.location, written, unchanged });
  auditEvent("evidence-materialized", { store: store.location, written: written.length, unchanged: unchanged.length });
  return report;
}

/**
 * One line for the `workspaceGit.evidence` signal: how many files the
 * repository's manifests record, and how many of their objects are absent
 * from the store — a presence read through the immutable owner (`verify`
 * proves every byte). A refusal (no work tree, a bad manifest, a refused
 * store) is the line itself, never a crash of the reader.
 */
export function evidenceSummary(root: string): string {
  try {
    const top = trackedTop(root);
    const manifests = evidenceManifests(top);
    if (manifests.length === 0) return "none: no evidence manifest is tracked";
    const recorded = recordedEvidence(top, manifests);
    const store = admitEvidenceStore(evidenceStoreLocation(), top);
    const missing = [...new Set([...recorded.values()].map((entry) => entry.sha256))].filter((digest) => readObject(store, digest) === undefined).length;
    return `${String(recorded.size)} file(s) recorded in ${String(manifests.length)} manifest(s); ${missing === 0 ? "every object is in the store" : `${String(missing)} object(s) missing from the store`} ${store.location}`;
  } catch (error) {
    if (!(error instanceof HarnessError)) throw error;
    return `unavailable: ${error.code}: ${error.message}`;
  }
}

/** One line for the read-only setting signal: where the store is and what named it. */
export function evidenceStoreSummary(): string {
  try {
    const setting = evidenceStoreSetting();
    return `${setting.location} (${setting.source === "environment" ? setting.variable : "the default"})`;
  } catch (error) {
    if (!(error instanceof HarnessError)) throw error;
    return `unavailable: ${error.code}: ${error.message}`;
  }
}

/** The repository top of `root` (a typed refusal outside a work tree). */
export function trackedTop(root: string): string {
  return requiredRepositoryToplevel(root, "evidence_repository_missing", "inherited");
}
