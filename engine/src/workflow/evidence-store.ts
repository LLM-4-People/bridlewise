/**
 * THE EVIDENCE STORE — raw evidence kept OUT of git, every byte of it still
 * verifiable and recoverable by the path a record cites.
 *
 * ── WHY ───────────────────────────────────────────────────────────────────
 *
 * A round's raw evidence (run logs, receipts, screenshots, transcripts) is
 * what its records cite, but it is large (the 2026-10-04 recovery round:
 * 1,890 files, ~201 MB) and never edited again. Committed, it would weigh on
 * every clone forever; dropped, every citation of it would dangle. So the
 * BYTES live in a content-addressed store outside every checkout, and the
 * repository commits only a MANIFEST of them: each file's recorded path,
 * sha256, size and mode. The records keep citing the path; the manifest
 * proves which bytes it named; the store hands them back. The mode is git's
 * (`0644`, or `0755` for an executable), so a manifest never depends on the
 * umask of the machine that ingested it.
 *
 * ── A MANIFEST LAYER, NOTHING MORE ────────────────────────────────────────
 *
 * This module owns no storage of its own. The store's place is a per-user
 * private home ({@link EVIDENCE_HOME}, the one private-home owner
 * `filesystem/private-home.ts`, which also admits the key home), and its
 * objects are the immutable owner's content-addressed files
 * (`filesystem/immutable-receipt.ts`: written once through a descriptor-held,
 * link-free private chain, 0600 in 0700 folders, read back only when they
 * hash to their address). What lives here is the manifest, its paths, and the
 * three verbs over them.
 *
 * - The STORE ({@link evidenceStoreSetting}): `ROOT_POLICY.workflow.evidenceStore`
 *   — the operator's `HARNESS_EVIDENCE_HOME`, else
 *   `$XDG_DATA_HOME/<relative>`, else `~/.local/share/<relative>`: outside
 *   the keep-out floor's wildcard, and kept out of every confined process
 *   wherever it is (`keep-out.ts` asks the same setting). Refused when it
 *   overlaps the repository or the system temp folder by identity, as a link,
 *   or open to other users.
 * - The MANIFEST ({@link parseEvidenceManifest}): a JSON document
 *   (`schema` {@link EVIDENCE_MANIFEST_SCHEMA}) named
 *   `ROOT_POLICY.workflow.evidenceStore.manifestName`, found wherever git
 *   owns one ({@link evidenceManifests}: tracked, or not yet staged), one entry per line, sorted by
 *   path; no path is recorded twice across the manifests. EVERY recorded path
 *   lies in its manifest's own evidence folder
 *   (`<the manifest's folder>/<folderName>/`, {@link evidenceFolderOf}),
 *   never names a `.git` or hooks segment, and is never absolute or escaping
 *   — refused when a manifest is READ, so every verb inherits it. It is
 *   GENERATED by {@link ingestEvidence}, never typed.
 * - The IGNORE RULE ({@link syncEvidenceIgnore}): git ignores each manifest's
 *   evidence folder through ONE generated block of the root `.gitignore`,
 *   derived from the same manifests (ingest and `harness sync` write it,
 *   `harness check` fails when it drifted; materialize refuses to write while
 *   it is stale) — the copies materialize writes can never be committed.
 * - The VERBS (`harness evidence …`, src/workflow/harness-commands.ts):
 *   `ingest` stores files (a folder: every regular file under it) and
 *   records them — idempotent, and a recorded path is NEVER given other
 *   bytes; `verify` proves every recorded object present, private and
 *   byte-exact; `materialize` writes recorded files back at their recorded
 *   paths (a folder prefix materializes everything under it), refusing to
 *   overwrite a different file. Every read and write inside the checkout goes
 *   through a folder held by descriptor and reached without following a link
 *   (`path-identity.ts` `openContainedFolder`): a linked parent is refused,
 *   missing folders are made one level at a time, and what is checked is
 *   what is read or written.
 *
 * Records link a stored file as `evidence:<recorded path>`
 * (src/workflow/record-links.ts resolves such a link against the manifests,
 * and `harness check` refuses a Markdown link that names neither a file of
 * the tree nor a recorded path). Every ingest, verify and materialize is an
 * audit event through central logging.
 */
